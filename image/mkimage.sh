#!/bin/bash
# Build a bootable BlankOS UEFI disk image from the [core] repository.
#
#   sudo image/mkimage.sh [--test] [--size 8G] [--pkgs "base linux grub"]
#
# Output: $OUT/image/blankos.img (raw GPT disk: ESP + ext4 root).
# --test adds a root autologin on the serial console plus the self-test
# script used by tests/boot-test.py. Never ship a --test image.
#
# The disk is assembled without loop devices (mkfs.ext4 -d, mtools,
# sfdisk on a file) so it works in containers and CI runners.
set -euo pipefail
source "$(dirname "$0")/../config/blankos.conf"
source "$BLANKOS_ROOT/tools/lib.sh"
need_root

test_image=0
size=8G
packages="base linux grub"
while (($#)); do
	case $1 in
		--test) test_image=1 ;;
		--size) size=$2; shift ;;
		--pkgs) packages=$2; shift ;;
		*) die "unknown option $1" ;;
	esac
	shift
done

work=$OUT/image
root=$work/root
img=$work/blankos.img
esp_mb=256
rm -rf "$work"
mkdir -p "$root"

cleanup() { umount_vkfs "$LFS"; }
trap cleanup EXIT
mount_vkfs "$LFS"
mkdir -p "$LFS/repo" "$LFS/target"
mountpoint -q "$LFS/repo"   || mount --bind "$REPO_OUT" "$LFS/repo"
mountpoint -q "$LFS/target" || mount --bind "$root" "$LFS/target"

msg "Installing packages into the image: $packages"
cat > "$LFS/tmp/image-pacman.conf" << EOF
[options]
Architecture = x86_64
SigLevel = Never
LocalFileSigLevel = Never
[core]
Server = file:///repo/core
EOF
install -d "$root"/var/{lib/pacman,cache/pacman/pkg} "$root"/{dev,proc,sys,run,tmp}
# shellcheck disable=SC2086
in_chroot "$LFS" pacman --root /target --config /tmp/image-pacman.conf \
	--cachedir /target/var/cache/pacman/pkg --noconfirm -Sy $packages
rm -rf "$root"/var/cache/pacman/pkg/*

msg "Configuring the image"
root_uuid=$(cat /proc/sys/kernel/random/uuid)
root_partuuid=$(cat /proc/sys/kernel/random/uuid)
esp_id=$(printf '%04X-%04X' $((RANDOM % 65536)) $((RANDOM % 65536)))

cat > "$root/etc/fstab" << EOF
# /etc/fstab: static file system information.
# <file system>      <dir>      <type>  <options>          <dump> <pass>
UUID=$root_uuid      /          ext4    defaults,noatime   0      1
UUID=$esp_id         /boot/efi  vfat    umask=0077         0      2
EOF
install -d "$root/boot/efi"
# First boot: systemd generates the machine id and applies presets.
printf 'uninitialized\n' > "$root/etc/machine-id"
in_chroot "$LFS" systemctl --root=/target preset-all

cmdline="root=PARTUUID=$root_partuuid rw console=tty0 console=ttyS0,115200 loglevel=4"
install -d "$root/boot/grub"
cat > "$root/boot/grub/grub.cfg" << EOF
# BlankOS boot menu (generated by image/mkimage.sh)
set default=0
set timeout=3
insmod part_gpt
insmod ext2
insmod all_video
search --no-floppy --fs-uuid --set=root $root_uuid

menuentry "BlankOS" {
	linux /boot/vmlinuz-linux $cmdline
}
EOF

if ((test_image)); then
	msg "Adding test hooks (serial autologin + self-test)"
	install -d "$root/etc/systemd/system/serial-getty@ttyS0.service.d"
	cat > "$root/etc/systemd/system/serial-getty@ttyS0.service.d/autologin.conf" << "EOF"
[Service]
ExecStart=
ExecStart=-/sbin/agetty -o '-p -f -- \\u' --noclear --autologin root --keep-baud 115200,57600,38400,9600 - $TERM
EOF
	install -Dm755 "$BLANKOS_ROOT/tests/selftest.sh" "$root/usr/local/bin/blankos-selftest"
fi

msg "Building the EFI loader"
# A standalone GRUB with an embedded config that finds the root fs and
# hands over to /boot/grub/grub.cfg there.
cat > "$LFS/tmp/grub-early.cfg" << EOF
search --no-floppy --fs-uuid --set=root $root_uuid
set prefix=(\$root)/boot/grub
configfile (\$root)/boot/grub/grub.cfg
EOF
in_chroot "$LFS" grub-mkstandalone -O x86_64-efi -o /tmp/BOOTX64.EFI \
	--modules="part_gpt ext2 fat search normal configfile linux all_video" \
	"boot/grub/grub.cfg=/tmp/grub-early.cfg"

msg "Assembling the disk image ($size)"
umount_vkfs "$LFS"
truncate -s "$size" "$img"
sfdisk -q "$img" << EOF
label: gpt
start=1MiB, size=${esp_mb}MiB, type=uefi, name="EFI"
start=$((1 + esp_mb))MiB, type=linux, uuid=$root_partuuid, name="BlankOS"
EOF
root_start=$(sfdisk -J "$img" | python3 -c 'import json,sys; p=json.load(sys.stdin)["partitiontable"]["partitions"][1]; print(p["start"], p["size"])')
read -r root_sector root_sectors <<< "$root_start"

esp=$work/esp.img
rm -f "$esp"
mkfs.vfat -C -F 32 -n BLANKOS -i "${esp_id/-/}" "$esp" $((esp_mb * 1024)) > /dev/null
export MTOOLS_SKIP_CHECK=1
mmd -i "$esp" ::/EFI ::/EFI/BOOT
mcopy -i "$esp" "$LFS/tmp/BOOTX64.EFI" ::/EFI/BOOT/BOOTX64.EFI
dd if="$esp" of="$img" bs=1M seek=1 conv=notrunc status=none

rootfs=$work/rootfs.img
mkfs.ext4 -q -F -L blankos -U "$root_uuid" -d "$root" "$rootfs" "$((root_sectors / 2))k"
dd if="$rootfs" of="$img" bs=512 seek="$root_sector" conv=notrunc,sparse status=none
rm -f "$esp" "$rootfs"

msg "Image ready: $img"
sfdisk -l "$img" | tail -n 3
